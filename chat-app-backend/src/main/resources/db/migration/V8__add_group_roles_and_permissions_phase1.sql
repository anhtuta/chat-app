ALTER TABLE public.group_participants
    ADD COLUMN role varchar(32) NOT NULL DEFAULT 'MEMBER';

INSERT INTO public.group_participants (group_id, user_id, joined_at, last_read_message_id, role)
SELECT g.id, g.created_by, g.created_at, NULL, 'LEADER'
FROM public."groups" g
WHERE NOT EXISTS (
    SELECT 1
    FROM public.group_participants gp
    WHERE gp.group_id = g.id
      AND gp.user_id = g.created_by
);

UPDATE public.group_participants gp
SET role = 'LEADER'
FROM public."groups" g
WHERE gp.group_id = g.id
  AND gp.user_id = g.created_by;

CREATE UNIQUE INDEX ux_group_participants_one_leader
    ON public.group_participants (group_id)
    WHERE role = 'LEADER';

