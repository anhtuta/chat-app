CREATE TABLE public.group_bans (
    id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id int8 NOT NULL,
    user_id int8 NOT NULL,
    banned_by int8 NOT NULL,
    reason varchar(500) NULL,
    banned_at timestamp(6) NOT NULL,
    CONSTRAINT uk_group_bans_group_user UNIQUE (group_id, user_id),
    CONSTRAINT fk_group_bans_group_id_groups FOREIGN KEY (group_id) REFERENCES public."groups"(id),
    CONSTRAINT fk_group_bans_user_id_users FOREIGN KEY (user_id) REFERENCES public.users(id),
    CONSTRAINT fk_group_bans_banned_by_users FOREIGN KEY (banned_by) REFERENCES public.users(id)
);

CREATE INDEX idx_group_bans_user_id
    ON public.group_bans (user_id);

CREATE TABLE public.group_join_links (
    id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id int8 NOT NULL,
    token_hash varchar(128) NOT NULL,
    created_by int8 NOT NULL,
    created_at timestamp(6) NOT NULL,
    expires_at timestamp(6) NULL,
    revoked_at timestamp(6) NULL,
    revoked_by int8 NULL,
    CONSTRAINT uk_group_join_links_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_group_join_links_group_id_groups FOREIGN KEY (group_id) REFERENCES public."groups"(id),
    CONSTRAINT fk_group_join_links_created_by_users FOREIGN KEY (created_by) REFERENCES public.users(id),
    CONSTRAINT fk_group_join_links_revoked_by_users FOREIGN KEY (revoked_by) REFERENCES public.users(id)
);

CREATE INDEX idx_group_join_links_group_active
    ON public.group_join_links (group_id, revoked_at, expires_at);

